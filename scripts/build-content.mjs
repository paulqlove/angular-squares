import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import matter from 'gray-matter';
import { marked } from 'marked';
import sanitizeHtml from 'sanitize-html';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const origin = 'https://quarterscore.com';
const blogDir = path.join(root, 'content', 'blog');
const clientRoutes = new Set(['dashboard', 'game/:gameId', '**']);
const pageLastmod = '2026-11-01';

const requiredFields = ['title', 'description', 'date', 'slug', 'ogImage'];

function readRoutes() {
  const source = fs.readFileSync(path.join(root, 'src', 'app', 'app.routes.ts'), 'utf8');
  const literals = [...source.matchAll(/path:\s*'([^']*)'/g)].map(match => match[1]);
  const marketing = [...source.matchAll(/marketingRoute\('([^']+)'\)/g)].map(match => match[1]);
  return [...literals, ...marketing];
}

function xmlEscape(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function loadPosts() {
  if (!fs.existsSync(blogDir)) {
    return [];
  }
  const files = fs.readdirSync(blogDir).filter(name => name.endsWith('.md')).sort();
  const posts = [];
  const slugs = new Set();
  for (const file of files) {
    const raw = fs.readFileSync(path.join(blogDir, file), 'utf8');
    const parsed = matter(raw);
    const data = parsed.data;
    if (data.draft === true) {
      continue;
    }
    if (data.date instanceof Date) {
      const year = data.date.getUTCFullYear();
      const month = String(data.date.getUTCMonth() + 1).padStart(2, '0');
      const day = String(data.date.getUTCDate()).padStart(2, '0');
      data.date = `${year}-${month}-${day}`;
    }
    for (const field of requiredFields) {
      if (typeof data[field] !== 'string' || data[field].trim() === '') {
        throw new Error(`${file} is missing frontmatter field "${field}"`);
      }
    }
    if (!/^\d{4}-\d{2}-\d{2}$/.test(data.date)) {
      throw new Error(`${file} date must be YYYY-MM-DD`);
    }
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(data.slug)) {
      throw new Error(`${file} slug must be lowercase words separated by hyphens`);
    }
    if (slugs.has(data.slug)) {
      throw new Error(`Duplicate blog slug: ${data.slug}`);
    }
    slugs.add(data.slug);
    const filenameSlug = file.replace(/\.md$/, '');
    if (filenameSlug !== data.slug) {
      throw new Error(`${file} filename must match slug "${data.slug}"`);
    }
    if (!data.ogImage.startsWith('/') && !data.ogImage.startsWith('https://')) {
      throw new Error(`${file} ogImage must be a root path or https URL`);
    }
    const rendered = marked.parse(parsed.content, { async: false });
    const html = sanitizeHtml(rendered, {
      allowedTags: sanitizeHtml.defaults.allowedTags.concat(['img', 'h1', 'h2']),
      allowedAttributes: {
        ...sanitizeHtml.defaults.allowedAttributes,
        a: ['href', 'name', 'target', 'rel'],
        img: ['src', 'alt', 'title', 'width', 'height']
      },
      transformTags: {
        a: (tagName, attribs) => {
          const href = attribs.href || '';
          if (/^https?:\/\//i.test(href)) {
            return {
              tagName: 'a',
              attribs: { href, rel: 'noopener noreferrer', target: '_blank' }
            };
          }
          if (href.startsWith('/') || href.startsWith('#')) {
            return { tagName: 'a', attribs: { href } };
          }
          throw new Error(`${file} has a link that is not relative or https: ${href}`);
        }
      }
    });
    posts.push({
      title: data.title.trim(),
      description: data.description.trim(),
      date: data.date,
      slug: data.slug,
      ogImage: data.ogImage.trim(),
      html
    });
  }
  posts.sort((a, b) => b.date.localeCompare(a.date));
  return posts;
}

function writePosts(posts) {
  const out = `import { BlogPost } from './blog-post.model';

/** Generated by scripts/build-content.mjs. Do not edit. */
export const BLOG_POSTS: BlogPost[] = ${JSON.stringify(posts, null, 2)};
`;
  fs.writeFileSync(path.join(root, 'src', 'app', 'features', 'blog', 'blog-posts.generated.ts'), out);
}

function publicPaths(routePaths, posts) {
  const paths = [];
  for (const routePath of routePaths) {
    if (clientRoutes.has(routePath)) {
      continue;
    }
    if (routePath === 'blog/:slug') {
      for (const post of posts) {
        paths.push(`/blog/${post.slug}`);
      }
      continue;
    }
    if (routePath.includes(':') || routePath.includes('*')) {
      throw new Error(`No prerender params for route "${routePath}". Add it to scripts/build-content.mjs.`);
    }
    paths.push(routePath === '' ? '/' : `/${routePath}`);
  }
  return paths;
}

function writePrerenderRoutes(paths) {
  fs.writeFileSync(path.join(root, 'prerender-routes.txt'), `${paths.join('\n')}\n`);
}

function writeSitemap(paths, posts) {
  const lastmod = new Map(posts.map(post => [`/blog/${post.slug}`, post.date]));
  const urls = paths.map(urlPath => {
    const loc = urlPath === '/' ? `${origin}/` : `${origin}${urlPath}`;
    const modified = lastmod.get(urlPath) ?? pageLastmod;
    return `  <url>\n    <loc>${xmlEscape(loc)}</loc>\n    <lastmod>${modified}</lastmod>\n  </url>`;
  });
  const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`;
  fs.writeFileSync(path.join(root, 'src', 'sitemap.xml'), xml);
}

function cdata(value) {
  return value.replaceAll(']]>', ']]]]><![CDATA[>');
}

function writeRss(posts) {
  const items = posts.map(post => {
    const link = `${origin}/blog/${post.slug}`;
    const pubDate = new Date(`${post.date}T12:00:00Z`).toUTCString();
    return `    <item>
      <title>${xmlEscape(post.title)}</title>
      <link>${xmlEscape(link)}</link>
      <guid>${xmlEscape(link)}</guid>
      <pubDate>${pubDate}</pubDate>
      <description>${xmlEscape(post.description)}</description>
      <content:encoded><![CDATA[${cdata(post.html)}]]></content:encoded>
    </item>`;
  });
  const rss = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:content="http://purl.org/rss/1.0/modules/content/">
  <channel>
    <title>Quarter Score Blog</title>
    <link>${origin}/blog</link>
    <description>Football squares notes from Quarter Score. Free games for friends and fans.</description>
    <language>en-us</language>
    <atom:link href="${origin}/rss.xml" rel="self" type="application/rss+xml"/>
${items.join('\n')}
  </channel>
</rss>
`;
  fs.writeFileSync(path.join(root, 'src', 'rss.xml'), rss);
}

async function writePdf() {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([612, 792]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const ink = rgb(0.06, 0.09, 0.16);
  page.drawText('Football squares', { x: 36, y: 752, size: 22, font: bold, color: ink });
  page.drawText('Blank 10 by 10 grid. Write names first. Draw digits 0-9 after the board is full.', {
    x: 36,
    y: 732,
    size: 10,
    font,
    color: ink
  });
  page.drawText('Home team: ______________________________', { x: 36, y: 708, size: 12, font, color: ink });
  page.drawText('Away team: ______________________________', { x: 320, y: 708, size: 12, font, color: ink });

  const left = 36;
  const top = 688;
  const cell = 46;
  const gridBottom = top - cell * 11;
  const gridRight = left + cell * 11;
  for (let line = 0; line <= 11; line += 1) {
    page.drawLine({
      start: { x: left, y: top - line * cell },
      end: { x: gridRight, y: top - line * cell },
      thickness: 1,
      color: ink
    });
    page.drawLine({
      start: { x: left + line * cell, y: top },
      end: { x: left + line * cell, y: gridBottom },
      thickness: 1,
      color: ink
    });
  }

  page.drawText('Columns: home last digit. Rows: away last digit. Write the drawn digits in the blank headers.', {
    x: 36,
    y: gridBottom - 18,
    size: 9,
    font,
    color: ink
  });
  page.drawText('Quarter Score never collects, holds, or pays out money.', {
    x: 36,
    y: 48,
    size: 9,
    font,
    color: ink
  });
  page.drawText('quarterscore.com/printable-football-squares', {
    x: 36,
    y: 34,
    size: 9,
    font,
    color: ink
  });

  const bytes = await pdf.save();
  const assetPath = path.join(root, 'src', 'assets', 'printable-football-squares.pdf');
  fs.writeFileSync(assetPath, bytes);
}

const routePaths = readRoutes();
const posts = loadPosts();
const paths = publicPaths(routePaths, posts);
writePosts(posts);
writePrerenderRoutes(paths);
writeSitemap(paths, posts);
writeRss(posts);
await writePdf();
console.log(`Content build: ${posts.length} post(s), ${paths.length} prerendered path(s).`);
